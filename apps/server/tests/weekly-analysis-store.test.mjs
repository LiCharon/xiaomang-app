import test from 'node:test';
import assert from 'node:assert/strict';
import { ObjectId } from 'mongodb';
import { connectTempDb, mongoUri } from './helpers/mongo-temp-db.mjs';
import { closeManagerDb } from '../api/_lib/manager/db.js';
import { closeMongoClient as closeTopicDb, buildLibraryAccount } from '../api/_lib/topicLibraryStore.js';
import { buildWeeklyAnalysisReport } from '../api/_lib/weeklyAnalysis.js';
import { confirmReviewMemory, deactivateReviewMemory, deleteWeeklyAnalysisReport, getActiveReviewMemory, getWeeklyAnalysisReport, listReviewMemoryVersions, listWeeklyAnalysisReports, saveWeeklyAnalysisReport } from '../api/_lib/weeklyAnalysisStore.js';
import { runWeeklyAnalysis } from '../api/_lib/weeklyAgentRunner.js';
import { weeklyInput, weeklyDictionary } from './helpers/weekly-fixture.mjs';
const OWNER_A = '661111111111111111111111';
const OWNER_B = '662222222222222222222222';
const CUSTOMER = '663333333333333333333333';
test('4.2 Mongo真实读写：存储隔离、并发幂等、确认历史、旧请求重试与停用', { skip: mongoUri ? false : '缺少 MongoDB' }, async t => {
  const { db, client, skipReason } = await connectTempDb(`xmweekly_${process.pid.toString(36)}${Date.now().toString(36)}`);
  if (!db) return t.skip(skipReason);
  t.after(async () => { await closeManagerDb(); await closeTopicDb(); await db.dropDatabase(); await client.close(); });
  await db.collection('customers').insertOne({ _id: new ObjectId(CUSTOMER), name: '周报测试客户' });
  const account = buildLibraryAccount({ report: { accountName: '对标账号', accountUrl: 'https://www.douyin.com/user/test', analyzedCount: 6,
    categories: weeklyDictionary.map((c, i) => ({ id: `c${i}`, name: c.name, subcategories: c.subcategories.map((s, j) => ({ id: `s${i}${j}`, name: s.name })) })) } });
  await db.collection('topic_libraries').insertOne({ managerId: new ObjectId(OWNER_A), customerId: CUSTOMER, customerName: '客户', accounts: [account] });
  const report = buildWeeklyAnalysisReport({ input: weeklyInput(), categoryDictionary: weeklyDictionary });
  const args = { ownerId: OWNER_A, customerId: CUSTOMER, report };
  const saved = await Promise.all(Array.from({ length: 5 }, () => saveWeeklyAnalysisReport(args)));
  assert.equal(new Set(saved.map(r => r.id)).size, 1, '并发保存只有一条');
  const id = saved[0].id;
  assert.equal((await listWeeklyAnalysisReports({ ownerId: OWNER_A }))[0].report, undefined);
  assert.equal(await getWeeklyAnalysisReport({ ownerId: OWNER_B, id }), null);
  assert.equal(await deleteWeeklyAnalysisReport({ ownerId: OWNER_B, id }), false);
  assert.equal(await getActiveReviewMemory({ customerId: CUSTOMER, platform: 'douyin' }), null, '保存周报不激活');
  await assert.rejects(() => confirmReviewMemory({ ownerId: OWNER_B, reportId: id, plan: report.plan, requestId: 'confirmation-test-0000' }), /无权/);
  const confirm = { ownerId: OWNER_A, reportId: id, plan: report.plan, requestId: 'confirmation-test-0001' };
  const versions = await Promise.all(Array.from({ length: 4 }, () => confirmReviewMemory(confirm)));
  assert.equal(new Set(versions.map(v => v.version.id)).size, 1, '并发确认同一请求幂等');
  const first = versions[0].version;
  assert.equal((await getActiveReviewMemory({ customerId: CUSTOMER, platform: 'douyin' })).id, first.id);
  assert.equal(await getActiveReviewMemory({ customerId: CUSTOMER, platform: 'wechat_channels' }), null, '跨平台隔离');
  assert.equal(await getActiveReviewMemory({ customerId: '664444444444444444444444', platform: 'douyin' }), null, '跨客户隔离');
  assert.equal((await listReviewMemoryVersions({ ownerId: OWNER_B, customerId: CUSTOMER, platform: 'douyin' })).length, 0);
  await assert.rejects(() => confirmReviewMemory({ ...confirm, notes: 'changed same request' }), /内容已变化/);
  const second = await confirmReviewMemory({ ...confirm, requestId: 'confirmation-test-0002', notes: '人工经验' });
  // Model two server processes issuing ObjectIds in the same second with opposite random prefixes.
  const versionCollection = db.collection('weekly_review_memory_versions');
  const secondDoc = await versionCollection.findOne({ _id: new ObjectId(second.version.id) });
  await versionCollection.deleteOne({ _id: secondDoc._id });
  secondDoc._id = new ObjectId(first.id.slice(0, 8) + '0000000000000000');
  await versionCollection.insertOne(secondDoc);
  await db.collection('weekly_review_memory_active').updateOne({ customerId: CUSTOMER, platform: 'douyin' }, { $set: { versionId: secondDoc._id } });
  second.version.id = String(secondDoc._id);
  assert.ok(second.version.id < first.id, '新版本ID也可能比旧版本小');
  await confirmReviewMemory(confirm);
  assert.equal((await getActiveReviewMemory({ customerId: CUSTOMER, platform: 'douyin' })).id, second.version.id, '旧请求重试不能覆盖新版本');
  await assert.rejects(() => deactivateReviewMemory({ ownerId: OWNER_B, customerId: CUSTOMER, platform: 'douyin', versionId: second.version.id }), /无权/);
  await deactivateReviewMemory({ ownerId: OWNER_A, customerId: CUSTOMER, platform: 'douyin', versionId: second.version.id });
  await confirmReviewMemory({ ...confirm, requestId: 'confirmation-test-0002', notes: '人工经验' });
  assert.equal(await getActiveReviewMemory({ customerId: CUSTOMER, platform: 'douyin' }), null, '重试已停用确认也不能复活');
  assert.equal((await listReviewMemoryVersions({ ownerId: OWNER_A, customerId: CUSTOMER, platform: 'douyin' })).length, 2, '历史仍保留');
  const heuristic = await runWeeklyAnalysis({ ownerId: OWNER_A, customerId: CUSTOMER, body: { ...weeklyInput(), fillTags: false }, agent: async () => { throw new Error('offline'); } });
  assert.equal(heuristic.analysisSource, 'heuristic'); assert.equal(heuristic.videos.length, 6);
  assert.ok(heuristic.warnings.some(w => w.includes('AI 建议未生成')));
  const agent = await runWeeklyAnalysis({ ownerId: OWNER_A, customerId: CUSTOMER, body: { ...weeklyInput(), fillTags: false }, agent: async () => ({ summary: '仅依据数据，下一周继续核对。', actions: ['复核低于1000的视频'] }) });
  assert.equal(agent.analysisSource, 'agent'); assert.deepEqual(agent.plan, heuristic.plan, '模型不能改比例');
  const missingSubcategory = weeklyInput(); missingSubcategory.rows[0].structureTags.subcategoryName = ''; missingSubcategory.rows[0].script = '真实测试文案';
  let labelsCalled = false;
  const supplemented = await runWeeklyAnalysis({ ownerId: OWNER_A, customerId: CUSTOMER, body: missingSubcategory, agent: async request => {
    if (request.interfaceName === 'deepseek:weekly-structure-tags') {
      labelsCalled = true;
      return { items: [{ id: 'v0', categoryName: '危机管理', subcategoryName: '入职合规', goldThreeSecondsType: 'pain' }] };
    }
    assert.equal(JSON.parse(request.user).videos[0].script, '真实测试文案', '复盘解释必须有真实文案证据');
    return { summary: '待确认', actions: [] };
  } });
  assert.equal(labelsCalled, true, '单独缺小类也触发补标签');
  assert.equal(supplemented.videos[0].structureTags.subcategoryName, '入职合规');
  assert.equal(supplemented.videos[0].structureTags.categoryName, '风险防御', '保留人工大类');
  assert.equal(supplemented.videos[0].structureTags.goldThreeSecondsType, 'fear', '保留人工结构类型');
  const dishonest = structuredClone(report); dishonest.summary.totals.plays.value = 999999;
  const resaved = await saveWeeklyAnalysisReport({ ...args, report: dishonest });
  assert.equal(resaved.report.summary.totals.plays.value, 27900, '保存重算客户端统计');
  await db.collection('topic_libraries').updateOne({ customerId: CUSTOMER }, { $set: { 'accounts.0.analyses.classification.categories.0.subcategories': [] } });
  await assert.rejects(() => confirmReviewMemory({ ...confirm, requestId: 'confirmation-test-0003' }), /分类已变化/, '确认前复查小类字典');
  assert.equal(await deleteWeeklyAnalysisReport({ ownerId: OWNER_A, id }), true);
});
